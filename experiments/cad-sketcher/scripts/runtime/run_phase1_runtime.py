#!/usr/bin/env python3
"""Phase-1 runtime-compatibility orchestrator (driver for results/runtime-compat.json).

Runs, in order, and records evidence for:
  1. Python ABI      — extract the pinned cp313 manylinux wheel to a scratch
                       --target dir; import + minimal solve under Blender 5.2.2's
                       bundled Python 3.13.13 (abi_smoke.py).
  2. Extension install — install the OFFICIAL CAD_Sketcher v0.32.1 linux_x64
                       release ZIP into an ISOLATED BLENDER_USER_RESOURCES dir via
                       `blender --command extension install-file -r user_default -e`.
  3. Extension enable  — blender --background probe (blender_enable_probe.py):
                       extension enabled, slvs importable in Blender, operators
                       registered.
  4. Startup impact  — 3x timed headless startups each, with and without the
                       extension installed+enabled (same user-dir conditions,
                       no --factory-startup), medians reported.

Scratch dirs live OUTSIDE the repo (default /home/z/cad-sketcher-eval-scratch/);
Blender's bundled Python site-packages is never touched. The committed envelope
results/runtime-compat.json is generated by this script — never hand-edited.

Usage:
    python3 run_phase1_runtime.py [--zip <path-to-release-zip>]
    (downloads the official v0.32.1 linux_x64 zip if not given)
"""

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
LANE = HERE.parent.parent
SCRATCH = Path(os.environ.get("CAD_SKETCHER_SCRATCH", "/home/z/cad-sketcher-eval-scratch"))
BLENDER = Path("/home/z/runtime/blender-5.2.2-linux-x64")
BLENDER_PY = BLENDER / "5.2" / "python" / "bin" / "python3.13"
UPSTREAM = LANE / ".upstream" / "CAD_Sketcher"
WHEEL = "wheels/slvs-3.2-cp313-cp313-manylinux_2_17_x86_64.manylinux2014_x86_64.whl"
WHEEL_SHA256 = "9ee04ff5a00482cef1751eed71658f4b01f605de42c56786373c7da9e5b25f80"
PIN_TAG = "v0.32.1"
PIN_COMMIT = "e7db7e6f94ad9dcaf2be03e849e1d3a2ac82e7a4"
RELEASE_URL = ("https://github.com/hlorus/CAD_Sketcher/releases/download/"
               "v0.32.1/CAD_Sketcher-0.32.1-linux_x64.zip")
RELEASE_SHA256_RECORDED = "c679cccd8ae955c440787e6be4a8eaebfb77cb1909eb8de04ffc182e97774541"

checks = []


def record(name, passed, detail=""):
    checks.append({"name": name, "pass": bool(passed), "detail": detail})
    print(f"{'PASS' if passed else 'FAIL'} {name}  {detail}")
    return bool(passed)


def run(cmd, env=None, timeout=300):
    t0 = time.time()
    p = subprocess.run(cmd, capture_output=True, text=True, env=env, timeout=timeout)
    return p, time.time() - t0


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--zip", default=None, help="pre-downloaded release zip path")
    args = ap.parse_args()

    SCRATCH.mkdir(parents=True, exist_ok=True)
    started = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    envelope = {
        "experiment": "runtime-compat",
        "issue_ref": "m3-eval phase 1 (CAD Sketcher evaluation)",
        "upstream": {
            "repo": "https://github.com/hlorus/CAD_Sketcher",
            "tag": PIN_TAG,
            "sha": PIN_COMMIT,
            "version": "0.32.1",
        },
        "host": {
            "cpus": os.cpu_count(),
            "mem_gb": round(os.sysconf("SC_PAGE_SIZE") * os.sysconf("SC_PHYS_PAGES") / 2**30, 1),
            "blender": "5.2.2 LTS (hash d13f752e3b9c built 2026-09-15)",
            "blender_python": "3.13.13",
            "note": "sandbox container",
        },
        "scratch_dir": str(SCRATCH),
        "command": "python3 experiments/cad-sketcher/scripts/runtime/run_phase1_runtime.py",
        "started_utc": started,
        "steps": {},
        "checks": [],
        "failures": [],
    }

    # ---- 1. Python ABI -------------------------------------------------------
    pytarget = SCRATCH / "pytarget"
    if pytarget.exists():
        shutil.rmtree(pytarget)
    wheel_path = UPSTREAM / WHEEL
    record("abi.wheel_pinned", sha256(wheel_path) == WHEEL_SHA256,
           f"{WHEEL} sha256 {'matches pin' if sha256(wheel_path) == WHEEL_SHA256 else 'MISMATCH'}")
    subprocess.run([str(BLENDER_PY), "-c",
                    f"import zipfile;zipfile.ZipFile({str(wheel_path)!r}).extractall({str(pytarget)!r})"],
                   check=True)
    env = dict(os.environ, PYTHONPATH=str(pytarget))
    abi_cmd = [str(BLENDER_PY), str(HERE / "abi_smoke.py")]
    p, dur = run(abi_cmd, env=env)
    abi_json = {}
    try:
        lines = (p.stdout or "").strip().splitlines()
        start = next(i for i, ln in enumerate(lines) if ln.startswith("{"))
        abi_json = json.loads("\n".join(lines[start:]))
    except Exception:
        pass
    envelope["steps"]["python_abi"] = {
        "command": f"PYTHONPATH={pytarget} {' '.join(abi_cmd)}",
        "exit": p.returncode,
        "seconds": round(dur, 2),
        "stdout_tail": (p.stdout or "")[-2000:],
        "stderr_tail": (p.stderr or "")[-2000:],
        "result": abi_json,
    }
    record("abi.smoke_solve", p.returncode == 0 and abi_json.get("all_passed") is True,
           f"exit {p.returncode}; solved p1={abi_json.get('solved', {}).get('p1')}, "
           f"dof={abi_json.get('solve_result', {}).get('dof')}")

    # ---- 2. Extension install (official release zip) -------------------------
    zip_path = Path(args.zip) if args.zip else SCRATCH / "CAD_Sketcher-0.32.1-linux_x64.zip"
    if not zip_path.is_file():
        urllib.request.urlretrieve(RELEASE_URL, zip_path)  # noqa: S310
    zip_sha = sha256(zip_path)
    envelope["release_zip"] = {"path": zip_path.name, "url": RELEASE_URL,
                               "size": zip_path.stat().st_size, "sha256": zip_sha}
    record("release.zip_downloaded", zip_path.is_file(),
           f"{zip_path.name} {zip_path.stat().st_size} bytes sha256 {zip_sha[:16]}...")

    userdir = SCRATCH / "ble_user_with_ext"
    if userdir.exists():
        shutil.rmtree(userdir)
    userdir.mkdir(parents=True)
    env_install = dict(os.environ, BLENDER_USER_RESOURCES=str(userdir))
    env_install.pop("BLENDER_USER_EXTENSIONS", None)
    install_cmd = [str(BLENDER / "blender"), "--command", "extension", "install-file",
                   "-r", "user_default", "-e", str(zip_path)]
    p, dur = run(install_cmd, env=env_install, timeout=600)
    out = (p.stdout or "") + (p.stderr or "")
    envelope["steps"]["extension_install"] = {
        "command": "BLENDER_USER_RESOURCES=<scratch>/ble_user_with_ext " + " ".join(
            [str(BLENDER / "blender")] + install_cmd[1:]),
        "exit": p.returncode,
        "seconds": round(dur, 2),
        "output_tail": out[-2000:],
    }
    record("extension.install", p.returncode == 0 and ("Installed" in out or "Reinstalled" in out),
           f"exit {p.returncode}; {out.strip()[:160]}")

    # ---- 3. Extension enable probe -------------------------------------------
    probe_out = SCRATCH / "blender_enable_probe.json"
    probe_cmd = [str(BLENDER / "blender"), "--background", "--python",
                 str(HERE / "blender_enable_probe.py"), "--", str(probe_out)]
    p, dur = run(probe_cmd, env=env_install, timeout=600)
    probe = {}
    if probe_out.is_file():
        probe = json.loads(probe_out.read_text())
    envelope["steps"]["extension_enable"] = {
        "command": "BLENDER_USER_RESOURCES=<scratch>/ble_user_with_ext " + " ".join(
            [str(BLENDER / "blender")] + probe_cmd[1:]),
        "exit": p.returncode,
        "seconds": round(dur, 2),
        "output_tail": ((p.stdout or "") + (p.stderr or ""))[-3000:],
        "result": probe,
    }
    record("extension.enable_probe", p.returncode == 0 and probe.get("all_passed") is True,
           f"exit {p.returncode}; probe all_passed={probe.get('all_passed')} "
           f"({sum(c.get('pass') for c in probe.get('checks', []))}/"
           f"{len(probe.get('checks', []))} checks)")

    # ---- 4. Startup impact ----------------------------------------------------
    def startup_times(user_dir, n=3):
        times = []
        for _ in range(n):
            e = dict(os.environ, BLENDER_USER_RESOURCES=str(user_dir))
            e.pop("BLENDER_USER_EXTENSIONS", None)
            _, dur = run([str(BLENDER / "blender"), "--background"], env=e, timeout=300)
            times.append(round(dur, 3))
        return times

    without_dir = SCRATCH / "ble_user_without_ext"
    if without_dir.exists():
        shutil.rmtree(without_dir)
    without_dir.mkdir(parents=True)

    t_without = startup_times(without_dir)
    t_with = startup_times(userdir)

    def median(xs):
        s = sorted(xs)
        return s[len(s) // 2]

    envelope["startup_impact"] = {
        "method": "3 runs each of `blender --background` (isolated BLENDER_USER_RESOURCES, "
                  "no --factory-startup so enabled extensions load); wall-clock seconds; medians",
        "without_extension": {"runs_s": t_without, "median_s": median(t_without), "user_dir": str(without_dir)},
        "with_extension": {"runs_s": t_with, "median_s": median(t_with), "user_dir": str(userdir)},
        "delta_median_s": round(median(t_with) - median(t_without), 3),
    }
    record("startup.timing_ran", len(t_without) == 3 and len(t_with) == 3,
           f"without {t_without} median {median(t_without)}s; "
           f"with {t_with} median {median(t_with)}s; delta {median(t_with) - median(t_without):+.3f}s")

    envelope["finished_utc"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    envelope["checks"] = checks
    envelope["failures"] = [c for c in checks if not c["pass"]]
    envelope["summary"] = {
        "all_passed": all(c["pass"] for c in checks),
        "abi_smoke": envelope["steps"]["python_abi"]["exit"] == 0,
        "extension_install": envelope["steps"]["extension_install"]["exit"] == 0,
        "extension_enable": envelope["steps"]["extension_enable"]["exit"] == 0 and probe.get("all_passed") is True,
        "startup_delta_median_s": envelope["startup_impact"]["delta_median_s"],
    }

    out_path = LANE / "results" / "runtime-compat.json"
    out_path.write_text(json.dumps(envelope, indent=2) + "\n")
    print(f"\nwrote {out_path}")
    return 0 if envelope["summary"]["all_passed"] else 1


if __name__ == "__main__":
    sys.exit(main())
